#!/usr/bin/env node
// Own generated shims/skill only; never replaces a user's unmarked files.
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const marker = 'Generated by Agent Relay installer';
const root = fileURLToPath(new URL('../', import.meta.url));
const cli = path.join(root, 'relay-cli.mjs');
const args = process.argv.slice(2), at = args.indexOf('--home');
const targetHome = at >= 0 ? path.resolve(args[at + 1]) : os.homedir();
const bin = path.join(targetHome, '.local', 'bin');
const unix = value => value.replace(/\\/g, '/');
const quote = value => "'" + value.replace(/'/g, "'\\''") + "'";
function writeOwned(filename, content, executable = false) {
  if (fs.existsSync(filename) && !fs.readFileSync(filename, 'utf8').includes(marker)) throw Error(`An unrelated file will not be replaced: ${filename}`);
  fs.mkdirSync(path.dirname(filename), { recursive: true }); fs.writeFileSync(filename, content, { mode: executable ? 0o755 : 0o644 });
  console.log(filename);
}
writeOwned(path.join(bin, 'relay.cmd'), `@echo off\r\nrem ${marker}\r\n"${process.execPath}" "${cli}" %*\r\n`);
writeOwned(path.join(bin, 'relay'), `#!/usr/bin/env bash\n# ${marker}\nexec ${quote(unix(process.execPath))} ${quote(unix(cli))} "$@"\n`, true);
for (const name of ['agent-relay-orchestrator', 'agent-relay-spec']) {
  const source = fs.readFileSync(path.join(root, 'skills', name, 'SKILL.md'), 'utf8');
  for (const area of ['.codex', '.claude']) writeOwned(path.join(targetHome, area, 'skills', name, 'SKILL.md'), `${source}\n<!-- ${marker}; source: ${unix(root)}skills/${name}/SKILL.md -->\n`);
}
console.log('Installed relay and the shared orchestration and specification skills. The existing ~/.local/bin PATH is used.');
